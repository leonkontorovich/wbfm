def check_question_mark_neurons(target_path: Optional[Path] = None, only_pending: bool = False):
    """Scan projects and display where unconfirmed '?' neurons from ID-transfer are located."""
    import pandas as pd
    import json

    project_dirs = []
    if target_path is not None:
        p = Path(target_path)
        if (p / "project_config.yaml").exists():
            project_dirs.append(p)
        elif p.is_dir():
            for sub in sorted(p.iterdir()):
                if sub.is_dir() and (sub / "project_config.yaml").exists():
                    project_dirs.append(sub)
                elif sub.is_dir():
                    for sub2 in sorted(sub.iterdir()):
                        if sub2.is_dir() and (sub2 / "project_config.yaml").exists():
                            project_dirs.append(sub2)
    else:
        recent_file = Path(__file__).resolve().parent.parent / ".recent_projects.json"
        if recent_file.exists():
            try:
                with open(recent_file, "r", encoding="utf-8") as f:
                    entries = json.load(f)
                for e in entries:
                    raw_p = e.get("path", "")
                    p = Path(raw_p).parent if raw_p.endswith(".yaml") else Path(raw_p)
                    if p.exists() and p not in project_dirs:
                        project_dirs.append(p)
            except Exception:
                pass

    if not project_dirs:
        print("No project directories found to inspect.")
        return

    print("=" * 110)
    print(f"{'WBFM ID-Transfer Neurons Review (? Status)':^110}")
    if target_path:
        print(f"Target directory: {target_path}")
    print("=" * 110)
    print(f"{'Recording Name':<44} | {'Total ID':<9} | {'Confirmed':<9} | {'Pending ?':<9} | {'Sample Uncertain IDs'}")
    print("-" * 110)

    total_projs = len(project_dirs)
    projs_with_qm = 0
    total_qm_count = 0

    for p in project_dirs:
        # Same file the dashboard counts (the newest annotation file, .xlsx or its .h5 copy)
        target_ann = newest_annotation_file(p)

        if not target_ann:
            if not only_pending:
                print(f"{p.name:<44} | {'[No IDs]':<9} | {'-':<9} | {'-':<9} | -")
            continue

        try:
            df = read_annotation_table(target_ann)
            id_col = "ID1" if "ID1" in df.columns else ("id1" if "id1" in df.columns else None)
            if not id_col:
                if not only_pending:
                    print(f"{p.name:<44} | {'[No ID1]':<9} | {'-':<9} | {'-':<9} | -")
                continue

            total_ided = df[df[id_col].astype(str).str.strip().ne('') & ~df[id_col].astype(str).str.lower().isin(['nan', 'none'])]
            qm = df[df[id_col].astype(str).str.contains(r'\?', na=False)]
            qm_count = len(qm)
            tot_count = len(total_ided)
            conf_count = tot_count - qm_count

            if qm_count > 0:
                projs_with_qm += 1
                total_qm_count += qm_count
                qm_names = qm[id_col].tolist()
                sample_str = ", ".join(qm_names[:6])
                if len(qm_names) > 6:
                    sample_str += f" (+{len(qm_names) - 6} more)"
                print(f"{p.name:<44} | {tot_count:<9} | {conf_count:<9} | {qm_count:<9} | {sample_str}")
            elif not only_pending:
                print(f"{p.name:<44} | {tot_count:<9} | {conf_count:<9} | {0:<9} | [All Confirmed]")
        except Exception as e:
            if not only_pending:
                print(f"{p.name:<44} | [Error: {e}]")

    print("-" * 110)
    print(f"Summary: {total_projs} recordings checked | {projs_with_qm} have pending '?' neurons | {total_qm_count} total '?' neurons")
    print("=" * 110)


def process_single_worm(worm_raw_dir: Path, output_parent: Optional[Path], experimenter: str, immobilized: bool = False,
                        force: bool = False, allow_default_config: bool = False) -> Optional[Dict[str, Any]]:
    """Process a single worm folder; returns None if it was skipped because it already has a project"""
    # Check before sanitizing, so a skipped recording is never renamed; projects record the dot-free folder name
    future_raw = worm_raw_dir.parent / worm_raw_dir.name.replace(".", "_")
    existing = find_existing_projects(future_raw, *project_search_parents(future_raw, output_parent))
    if existing and not force:
        logger.warning(f"Skipping {worm_raw_dir.name}: already analysed in "
                       f"{', '.join(str(p) for p in existing)} (use --force to create another project)")
        return None
    clean_raw = sanitize_raw_folder(worm_raw_dir, allow_default_config=allow_default_config)
    exp = clean_raw.name if experimenter == "LeonK" else experimenter  # name after the dot-free rename
    proj_dir, proj_linux = initialize_project(clean_raw, output_parent, exp, immobilized)
    job_id = submit_dual_pipeline(proj_dir, proj_linux)
    return {
        "raw": worm_raw_dir.name,
        "project_dir": proj_dir,
        "project_linux": proj_linux,
        "job_id": job_id
    }


