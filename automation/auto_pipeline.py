def win_to_linux_path(win_path: Path) -> str:
    """Convert Windows scratch path (Z:\\...) to cluster Linux path (/lisc/data/scratch/...)."""
    p_str = str(win_path).replace("\\", "/")
    if p_str.lower().startswith("z:/neurobiology/zimmer"):
        return SCRATCH_LINUX_ROOT + p_str[len("z:/neurobiology/zimmer"):]
    if p_str.lower().startswith("z:/"):
        return SCRATCH_LINUX_ROOT + p_str[len("z:"):]
    if "//samba.lisc.univie.ac.at/scratch/neurobiology/zimmer" in p_str:
        idx = p_str.find("/neurobiology/zimmer")
        return SCRATCH_LINUX_ROOT + p_str[idx + len("/neurobiology/zimmer"):]
    if p_str.startswith("/lisc/"):
        return p_str
    # e.g. C:\Users\...: the cluster cannot see it, and sending it anyway only fails later and less clearly
    raise ValueError(f"{win_path} is not on the cluster scratch share (Z:\\ or /lisc/...); "
                     f"copy the data to Z:\\neurobiology\\zimmer\\... first")


def linux_to_win_path(linux_path: str) -> Path:
    """Convert cluster Linux path (/lisc/data/scratch/...) to Windows scratch path (Z:\\...)."""
    l_str = linux_path.replace("\\", "/")
    if l_str.startswith(SCRATCH_LINUX_ROOT):
        rel = l_str[len(SCRATCH_LINUX_ROOT):].lstrip("/")
        return scratch_win_root() / Path(rel.replace("/", "\\"))
    return Path(linux_path)


# Oct 2026 LiSC audit: segmentation peaked at 13.2G RAM / 8.3 cores / ~12h (see AGENTS.md, invariant 9)
SEGMENTATION_RESOURCES = {"time": "0-16:00:00", "mem": "48G", "cpus_per_task": "12"}


def right_size_segmentation_resources(text: str) -> str:
    """Rewrite time/mem/cpus_per_task of the (alt_)segmentation blocks of a cluster_config.yaml.

    Line-based on purpose: keeps comments, key order and line endings of the project's file intact."""
    out, in_block = [], False
    for line in text.split("\n"):
        stripped = line.strip()
        if line and not line[0].isspace() and not stripped.startswith("#"):
            in_block = stripped in ("segmentation:", "alt_segmentation:")
        elif in_block:
            m = re.match(r"^(\s+)(time|mem|cpus_per_task):\s*\S+(.*)$", line)
            if m:
                line = f"{m.group(1)}{m.group(2)}: {SEGMENTATION_RESOURCES[m.group(2)]}{m.group(3)}"
        out.append(line)
    return "\n".join(out)


def run_ssh_cmd(cmd: str, check: bool = True, timeout: int = 300) -> subprocess.CompletedProcess:
    """Run remote command on LISC cluster using OpenSSH (bounded: an unreachable cluster fails instead of hanging)."""
    full_cmd = ["ssh", "-o", "ConnectTimeout=15", CLUSTER_SSH_HOST, cmd]
    logger.debug(f"SSH: {cmd}")
    try:
        res = subprocess.run(full_cmd, capture_output=True, text=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        raise RuntimeError(f"Remote command timed out after {timeout}s: {cmd[:80]}")
    if check and res.returncode != 0:
        logger.error(f"Remote command failed (code {res.returncode}): {res.stderr.strip()}")
        raise RuntimeError(f"Remote command failed: {res.stderr.strip()}")
    return res


def is_direct_worm_folder(folder: Path) -> bool:
    """Check if folder directly contains channel stores or BigTIFFs for a single worm."""
    if not folder.is_dir():
        return False
    subdirs = [d.name.lower() for d in folder.iterdir() if d.is_dir()]
    ch0_dirs = [s for s in subdirs if s.endswith("_ch0") or "ch0" in s]
    if len(ch0_dirs) == 1:
        return True
    files = [f.name.lower() for f in folder.iterdir() if f.is_file()]
    if any(f.endswith("_ch0.btf") or f.endswith("_ch0.tif") for f in files):
        return True
    return False


def discover_worm_folders(target_dir: Path) -> List[Path]:
    """Discover all worm recording folders under target_dir (handles single or batch)."""
    if is_direct_worm_folder(target_dir):
        return [target_dir]

    found = []
    for sub in target_dir.iterdir():
        if sub.is_dir() and is_direct_worm_folder(sub):
            # Skip alignment, background, notes
            lower = sub.name.lower()
            if any(skip in lower for skip in ["align", "backgr", "note", "calib"]):
                logger.info(f"Skipping non-worm reference folder: {sub.name}")
                continue
            found.append(sub)

    if not found:
        # Recursive fallback (depth 2)
        for sub in target_dir.glob("*/*"):
            if sub.is_dir() and is_direct_worm_folder(sub):
                lower = sub.name.lower()
                if not any(skip in lower for skip in ["align", "backgr", "note", "calib"]):
                    found.append(sub)

    return sorted(found, key=lambda p: p.stat().st_mtime)


def require_visible_folder(folder: Path, what: str = "Raw folder") -> Path:
    """Stop with an explanation (not a traceback) if Windows cannot see the folder"""
    if folder.is_dir():
        return folder
    hint = ""
    if str(folder).replace("/", "\\").lower().startswith("z:\\"):
        hint = ("\n  If it exists on the cluster, a parent folder may have been moved to /lisc/archive and replaced by a "
                "symlink, which the Z: share cannot follow (e.g. LeonK\\raw and LeonK\\Lit_raw). Put recordings to "
                "analyse in a real folder on scratch, e.g. Z:\\neurobiology\\zimmer\\LeonK\\raw_incoming\\<date>.")
    logger.error(f"{what} not found or not visible from Windows: {folder}{hint}")
    sys.exit(1)


def find_latest_raw_folder() -> Path:
    """Find newest unanalyzed raw recording or batch folder."""
    # Where plain `go` looks for new recordings: WBFM_RAW_ROOT (e.g. set in launcher_settings.local.bat), else LeonK\raw
    configured = os.environ.get("WBFM_RAW_ROOT", "").strip().strip('"')
    raw_root = require_visible_folder(Path(configured) if configured else scratch_win_root() / "LeonK" / "raw",
                                      "Raw root for auto-detection (WBFM_RAW_ROOT)")

    worms = discover_worm_folders(raw_root)
    if not worms:
        raise FileNotFoundError(f"No valid raw acquisition folders found in {raw_root}")

    latest = worms[-1]
    logger.info(f"Auto-detected newest recording: {latest}")
    return latest


# Channel folder names: whole-token matches only, so e.g. "registered" or "filtered" never count as "red"
_CH0_TOKEN = re.compile(r"(?:^|[^a-z0-9])(?:ch0|channel0|red)(?:[^a-z0-9]|$)")
_CH1_TOKEN = re.compile(r"(?:^|[^a-z0-9])(?:ch1|channel1|green)(?:[^a-z0-9]|$)")


_CHANNEL_SUFFIX = re.compile(r"[_\-\s]*(?:ch|channel)[01]\b.*$|[_\-\s]*(?:red|green)$", re.IGNORECASE)


def _channel_base_name(name: str) -> str:
    """'worm1-ch0' / 'worm1_red' / 'x_Ch0_old' -> 'worm1' / 'worm1' / 'x' (the part before the channel marker)"""
    return _CHANNEL_SUFFIX.sub("", name) or name


def _pick_channel_folder(subdirs: List[Path], exact_suffix: str, token: "re.Pattern", raw_dir: Path) -> Optional[Path]:
    exact = [d for d in subdirs if d.name.endswith(exact_suffix)]
    candidates = exact or [d for d in subdirs if token.search(d.name.lower())]
    if len(candidates) > 1:
        raise ValueError(f"Several folders in {raw_dir} look like the {exact_suffix[1:]} channel: "
                         f"{', '.join(d.name for d in candidates)}. Move the extra one(s) out of the worm folder.")
    return candidates[0] if candidates else None


def sanitize_raw_folder(raw_dir: Path, allow_default_config: bool = False, dry_run: bool = False) -> Path:
    """
    Pre-flight sanitization of a raw acquisition folder: dot-free folder name, channel folders ending in _Ch0/_Ch1,
    both channels present, and an acquisition config.yaml.

    allow_default_config: if config.yaml is missing, write DEFAULT_CONFIG_YAML_CONTENT (assumed acquisition values)
        instead of stopping. Off by default: wrong exposure/flyback values silently corrupt the physical units.
    dry_run: only log what would be renamed or written; change nothing.
    """
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw directory not found: {raw_dir}")
    prefix = "[dry-run] would rename" if dry_run else "Renaming"

    def rename(src: Path, dst: Path) -> Path:
        logger.info(f"{prefix} {src.name} -> {dst.name}")
        return src if dry_run else src.rename(dst)

    # 1. Remove illegal dots in directory name
    name = raw_dir.name
    if "." in name:
        logger.warning(f"Directory name contains dots: {name}")
        raw_dir = rename(raw_dir, raw_dir.parent / name.replace(".", "_"))

    # 2. Detect and normalize channels: a folder already ending in _Ch0/_Ch1 wins; otherwise exactly one folder may
    # look like that channel (several candidates, e.g. 'worm4-Ch0' and 'Ch0_old', is an error rather than a guess)
    subdirs = sorted(p for p in raw_dir.iterdir() if p.is_dir())
    ch0_folder = _pick_channel_folder(subdirs, "_Ch0", _CH0_TOKEN, raw_dir)
    ch1_folder = _pick_channel_folder([d for d in subdirs if d != ch0_folder], "_Ch1", _CH1_TOKEN, raw_dir)

    # Normalize subfolder names to end strictly with _Ch0 and _Ch1
    if ch0_folder and not ch0_folder.name.endswith("_Ch0"):
        ch0_folder = rename(ch0_folder, raw_dir / f"{_channel_base_name(ch0_folder.name)}_Ch0")

    if ch1_folder and not ch1_folder.name.endswith("_Ch1"):
        ch1_folder = rename(ch1_folder, raw_dir / f"{_channel_base_name(ch1_folder.name)}_Ch1")

    # 3. Verify channel data integrity
    if not (ch0_folder and ch1_folder):
        btf0 = list(raw_dir.glob("*_Ch0*.btf")) or list(raw_dir.glob("*_Ch0*.tif"))
        btf1 = list(raw_dir.glob("*_Ch1*.btf")) or list(raw_dir.glob("*_Ch1*.tif"))
        if not (btf0 and btf1):
            raise ValueError(f"Could not identify both channels (_Ch0 and _Ch1) in {raw_dir}")
        logger.info(f"Verified BigTIFF channels: {btf0[0].name}, {btf1[0].name}")
    else:
        tifs0 = list(ch0_folder.glob("*.tif"))
        tifs1 = list(ch1_folder.glob("*.tif"))
        if not (tifs0 and tifs1):
            raise ValueError(f"Missing .tif files in {ch0_folder.name} or {ch1_folder.name}")
        logger.info(f"Verified NDTiff stores: Ch0 ({len(tifs0)} tifs), Ch1 ({len(tifs1)} tifs)")

    # 4. Ensure acquisition config.yaml exists
    cfg_file = raw_dir / "config.yaml"
    if cfg_file.exists():
        logger.info(f"Found existing config.yaml in {raw_dir.name} [OK]")
    elif allow_default_config:
        logger.warning(f"config.yaml missing in {raw_dir.name}; "
                       f"{'[dry-run] would write' if dry_run else 'writing'} the default template "
                       f"(ASSUMED values: exposure 20 ms, 22 z-planes, 1 flyback plane discarded)")
        if not dry_run:
            with open(cfg_file, "w") as f:
                f.write(DEFAULT_CONFIG_YAML_CONTENT)
    else:
        msg = (f"config.yaml missing in {raw_dir}. Acquisition values (exposure_time, z_step_size, num_z_planes, "
               f"flyback planes) cannot be guessed safely: copy the acquisition's config.yaml there, or rerun with "
               f"--default-config to write the template with ASSUMED values (exposure 20 ms, 22 planes, 1 flyback).")
        if dry_run:
            logger.error(f"[dry-run] {msg}")
        else:
            raise FileNotFoundError(msg)

    return raw_dir


def _load_physical_unit_overrides(raw_dir: Path) -> str:
    """Read the acquisition config.yaml in the raw folder and build sacred CLI
    overrides for the physical_units the project template requires.
    `exposure_time` has no default on the cluster template and must be passed
    explicitly, or 0a-create_new_project.py raises IncompleteConfigFileError."""
    cfg_file = raw_dir / "config.yaml"
    if not cfg_file.exists():
        return ""
    with open(cfg_file, "r") as f:
        acq = yaml.safe_load(f) or {}

    overrides = []
    exposure_time = acq.get("exposure_time")
    if exposure_time is not None:
        overrides.append(f"physical_units.exposure_time={exposure_time}")
    z_step_size = acq.get("z_step_size")
    if z_step_size is not None:
        overrides.append(f"physical_units.zimmer_um_per_pixel_z={z_step_size}")
    return " ".join(overrides)


def default_output_parent(raw_dir: Path) -> Path:
    """Analysis<date of the raw batch folder>, or Analysis_<today> if the raw parent is not a date"""
    parent_name = raw_dir.parent.name
    if re.match(r"^\d{6,8}$", parent_name):
        return scratch_win_root() / "LeonK" / f"Analysis{parent_name}"
    return scratch_win_root() / "LeonK" / f"Analysis_{time.strftime('%Y%m%d')}"


_PARENT_DATA_FOLDER = re.compile(r"^parent_data_folder:[ \t]*(?:\r?\n[ \t]+)?(\S+)", re.MULTILINE)


def project_raw_folder(project_dir: Path) -> Optional[str]:
    """The raw folder (cluster path) a project was created from: parent_data_folder in its project_config.yaml"""
    try:
        text = (project_dir / "project_config.yaml").read_text(errors="ignore")
    except OSError:
        return None
    try:
        value = (yaml.safe_load(text) or {}).get("parent_data_folder")
    except Exception:  # unusual tags etc.: fall back to the plain-text form the template writes
        m = _PARENT_DATA_FOLDER.search(text)
        value = m.group(1).strip("'\"") if m else None
    return str(value).strip().rstrip("/") if value else None


def find_existing_projects(raw_dir: Path, *search_parents: Optional[Path]) -> List[Path]:
    """Projects directly inside any of search_parents that were created from raw_dir"""
    raw_linux = win_to_linux_path(raw_dir).rstrip("/")
    found = []
    for parent in search_parents:
        if parent is None or not Path(parent).is_dir():
            continue
        for p in sorted(Path(parent).iterdir()):
            if p.is_dir() and project_raw_folder(p) == raw_linux:
                found.append(p)
    return found


def project_search_parents(raw_dir: Path, output_parent: Optional[Path]) -> List[Path]:
    """Where an earlier `go` may have put this recording's project: the --output-parent (if given), the default parent
    and every LeonK/Analysis* folder (projects moved elsewhere afterwards are not found)"""
    parents = [Path(output_parent)] if output_parent is not None else []
    parents.append(default_output_parent(raw_dir))
    try:
        parents += sorted(p for p in (scratch_win_root() / "LeonK").glob("Analysis*") if p.is_dir())
    except OSError:
        pass
    unique = []
    for p in parents:
        if p not in unique:
            unique.append(p)
    return unique


def initialize_project(raw_dir: Path, output_parent_dir: Optional[Path] = None, experimenter: str = "LeonK", immobilized: bool = False) -> Tuple[Path, str]:
    """Initialize WBFM project on LISC cluster and configure for dual tracking."""
    raw_linux = win_to_linux_path(raw_dir)

    if output_parent_dir is None:
        output_parent_dir = default_output_parent(raw_dir)

    output_parent_dir.mkdir(parents=True, exist_ok=True)
    out_linux_parent = win_to_linux_path(output_parent_dir)

    logger.info(f"Initializing WBFM project:")
    logger.info(f"  Raw:     {raw_linux}")
    logger.info(f"  Output:  {out_linux_parent}")

    physical_unit_overrides = _load_physical_unit_overrides(raw_dir)

    init_cmd = (
        f"{CLUSTER_ENV_PYTHON} "
        f"{SCRATCH_LINUX_ROOT}/wbfm/code/wbfm/wbfm/scripts/0a-create_new_project.py with "
        f"parent_data_folder='{raw_linux}' "
        f"project_dir='{out_linux_parent}' "
        f"experimenter='{experimenter}' "
        f"{physical_unit_overrides}"
    )
    before_init_ts = time.time()
    run_ssh_cmd(init_cmd)
    time.sleep(3)

    matching = [
        p for p in output_parent_dir.iterdir()
        # Projects are named "<experimenter>-<raw name>"; the "-" keeps worm1 from matching worm10-...
        if p.is_dir() and p.name.startswith(experimenter + "-") and (p / "project_config.yaml").exists()
    ]
    if not matching:
        matching = [
            p for p in output_parent_dir.iterdir()
            if p.is_dir() and (p / "project_config.yaml").exists()
        ]
    if not matching:
        raise RuntimeError(f"No project directory found inside {output_parent_dir} after initialization")

    # NOTE: st_mtime is unreliable here - copytree() from new_project_defaults preserves the
    # template files' original mtimes, so a brand-new project can appear "older" than an
    # existing, already-completed sibling project of the same worm (whose directory mtime was
    # bumped by e.g. a later PIPELINE_COMPLETE.flag write). Use directory creation time
    # (st_ctime, which Windows sets to first-seen time and is NOT touched by copytree) instead,
    # and restrict to directories actually created by *this* call to avoid silently picking a
    # stale pre-existing project.
    just_created = [p for p in matching if p.stat().st_ctime >= before_init_ts - 5]
    if len(just_created) == 1:
        matching = just_created
    elif len(just_created) > 1:
        raise RuntimeError(
            f"Ambiguous project creation: {len(just_created)} directories matching '{experimenter}' "
            f"in {output_parent_dir} all appear freshly created ({[p.name for p in just_created]}); "
            f"refusing to guess which one is correct."
        )
    elif len(matching) > 1:
        raise RuntimeError(
            f"Could not identify the newly created project directory for '{experimenter}' in "
            f"{output_parent_dir}: {len(matching)} pre-existing candidates found "
            f"({[p.name for p in matching]}) and none appear freshly created. Refusing to guess "
            f"and silently reuse a stale project."
        )

    project_dir = matching[0]
    project_linux = win_to_linux_path(project_dir)
    logger.info(f"Project initialized: {project_dir.name}")

    # Set snakemake_config.yaml
    smk_cfg = project_dir / "snakemake" / "snakemake_config.yaml"
    if smk_cfg.exists():
        with open(smk_cfg, "r") as f:
            c = f.read()
        c = re.sub(r"use_barlow_tracker:\s*true", "use_barlow_tracker: false", c, flags=re.IGNORECASE)
        c = re.sub(r"barlow_model_path:\s*.*", f"barlow_model_path: {DEFAULT_BARLOW_MODEL}", c)
        with open(smk_cfg, "w") as f:
            f.write(c)
        logger.info("Configured snakemake_config.yaml: SuperGlue + Barlow dual tracking [OK]")

    # The master job's final "RUNME.sh -s barlow_embedding" call otherwise re-runs the full segmentation:
    # once masks exist, pipeline.smk's ruleorder switches segmentation -> alt_segmentation, whose smaller
    # input set trips snakemake's default "input" rerun trigger (~6h wasted, and masks.zarr is overwritten
    # after traces were already extracted from it). Restrict that call to mtime-based rerun decisions.
    runme = project_dir / "snakemake" / "RUNME.sh"
    if runme.exists():
        with open(runme, "r", newline="") as f:
            c = f.read()
        if "--rerun-triggers mtime" not in c:
            patch = (
                'if [ "$RULE" = "barlow_embedding" ]; then\n'
                '    SNAKEMAKE_OPT="$SNAKEMAKE_OPT --rerun-triggers mtime"\n'
                'fi\n'
            )
            c, n = re.subn(r"^(NUM_JOBS_TO_SUBMIT=.*\n)", lambda m: m.group(1) + patch, c, count=1, flags=re.MULTILINE)
            if n:
                with open(runme, "w", newline="") as f:
                    f.write(c)
                logger.info("Configured RUNME.sh: barlow_embedding uses --rerun-triggers mtime (no re-segmentation) [OK]")
            else:
                logger.warning(f"Could not patch {runme}; barlow_embedding will re-run segmentation!")
    else:
        logger.warning(f"Expected RUNME.sh not found at {runme}; barlow_embedding will re-run segmentation!")

    # Right-size the segmentation Slurm request (the template still asks for 256G / 40 cores / 36h)
    cluster_cfg = project_dir / "snakemake" / "cluster_config.yaml"
    if cluster_cfg.exists():
        with open(cluster_cfg, "r", newline="") as f:
            c = f.read()
        c_new = right_size_segmentation_resources(c)
        if c_new != c:
            with open(cluster_cfg, "w", newline="") as f:
                f.write(c_new)
            logger.info(f"Configured cluster_config.yaml: segmentation uses {SEGMENTATION_RESOURCES} [OK]")

    if immobilized:
        seg_cfg = project_dir / "1-segmentation" / "segment_config.yaml"
        if seg_cfg.exists():
            with open(seg_cfg, "r") as f:
                c = f.read()
            c = re.sub(
                r"max_number_of_objects:\s*\d+.*",
                "max_number_of_objects: 220 # Immobilized recordings that include the tail",
                c,
            )
            with open(seg_cfg, "w") as f:
                f.write(c)
            logger.info("Configured segment_config.yaml: max_number_of_objects=220 (immobilized) [OK]")
        else:
            logger.warning(f"Expected segment_config.yaml not found at {seg_cfg}; max_number_of_objects NOT set to 220!")

    return project_dir, project_linux


def submit_dual_pipeline(project_dir: Path, project_linux: str) -> str:
    """Submit the resilient master Slurm execution script."""
    worm_name = project_dir.name[:12]
    
    # Generate test YAML for ID transfer
    id_test_yaml_linux = f"{project_linux}/3-tracking/id_transfer_target.yaml"
    test_yaml_content = f"""recordings:
  - name: {project_dir.name}
    path: {project_linux}
    side: unknown
    role: predict
    include: true
"""
    (project_dir / "3-tracking").mkdir(parents=True, exist_ok=True)
    with open(project_dir / "3-tracking" / "id_transfer_target.yaml", "w") as f:
        f.write(test_yaml_content)

    master_script = f"""#!/bin/bash
#SBATCH --job-name=wbfm_{worm_name}
#SBATCH --output={project_linux}/snakemake/slurm_master_%j.out
#SBATCH --error={project_linux}/snakemake/slurm_master_%j.err
#SBATCH --time=48:00:00
#SBATCH --cpus-per-task=2
#SBATCH --mem=8G
#SBATCH --partition=xeon_0384

export CONDA_PREFIX={SCRATCH_LINUX_ROOT}/.conda/envs/wbfm
export PATH="$CONDA_PREFIX/bin:$PATH"
export LD_LIBRARY_PATH="$CONDA_PREFIX/lib:$LD_LIBRARY_PATH"
export OPENBLAS_NUM_THREADS=1
export OMP_NUM_THREADS=1
export MKL_NUM_THREADS=1

cd "{project_linux}/snakemake"
echo "=== WBFM Pipeline Master Job Started at $(date) ==="
echo "Host: $(hostname)"
echo "Project Directory: {project_linux}"

echo "[1/3] Running Initial Pipeline Checks..."
snakemake -s pipeline.smk --unlock || true

echo "[2/3] Running Main Snakemake Pipeline (StarDist Segmentation + SuperGlue Tracking + Calcium Traces)..."
bash RUNME.sh
STATUS_MAIN=$?
if [ $STATUS_MAIN -ne 0 ]; then
    echo "[WARNING] Main pipeline exited with code $STATUS_MAIN. Unlocking and retrying once..."
    snakemake -s pipeline.smk --unlock || true
    bash RUNME.sh
    STATUS_MAIN=$?
fi

echo "[3/3] Running Barlow Embedding (GPU Feature Extraction for ID Transfer)..."
# Only generate barlow_embedding (embedding.zarr + feature indices) needed for ID transfer; bypass redundant Barlow tracking
bash RUNME.sh -s barlow_embedding
STATUS_BARLOW=$?
if [ $STATUS_BARLOW -ne 0 ]; then
    echo "[WARNING] Barlow embedding exited with code $STATUS_BARLOW"
fi

rm -f "{project_linux}/PIPELINE_FAILED.flag"
if [ $STATUS_MAIN -eq 0 ] && [ $STATUS_BARLOW -eq 0 ]; then
    echo "PIPELINE_COMPLETE" > "{project_linux}/PIPELINE_COMPLETE.flag"
    echo "=== WBFM Pipeline Master Completed at $(date) ==="
else
    echo "main=$STATUS_MAIN barlow=$STATUS_BARLOW" > "{project_linux}/PIPELINE_FAILED.flag"
    echo "=== WBFM Pipeline Master FAILED at $(date) (main=$STATUS_MAIN, barlow=$STATUS_BARLOW) ==="
    exit 1
fi
"""

    remote_submission = f"cat << 'EOF' | sbatch\n{master_script}EOF"
    res = run_ssh_cmd(remote_submission)
    job_id = "UNKNOWN"
    for line in res.stdout.splitlines():
        if "Submitted batch job" in line:
            job_id = line.strip().split()[-1]
            break

    logger.info(f"Dispatched master Slurm job: ID {job_id}")
    if job_id != "UNKNOWN":
        # 'go status' uses this to show this project's master job (its children are found by working directory)
        try:
            with open(project_dir / "snakemake" / MASTER_JOBID_FILE, "a") as f:
                f.write(job_id + "\n")
        except OSError as e:
            logger.warning(f"Could not record master job ID {job_id}: {e}")
    return job_id


MASTER_JOBID_FILE = "master_jobid.txt"
SQUEUE_FORMAT = "%i|%j|%T|%M|%R|%Z"  # parsed by select_project_jobs


def select_project_jobs(squeue_lines: List[str], project_linux: Optional[str], master_ids) -> List[str]:
    """
    This project's jobs from `squeue -h -o SQUEUE_FORMAT` lines: its master job(s) by ID, and the Snakemake rule jobs
    (named after the rule, e.g. segmentation) by their working directory inside the project
    """
    jobs = []
    for line in squeue_lines:
        parts = line.strip().split("|", 5)
        if len(parts) < 6:
            continue
        job_id, name, state, elapsed, reason, workdir = (x.strip() for x in parts)
        workdir = workdir.rstrip("/")
        in_project = bool(project_linux) and (workdir == project_linux or workdir.startswith(project_linux + "/"))
        if job_id in master_ids or in_project:
            jobs.append(f"{job_id:>10}  {name:<20} {state:<10} {elapsed:>10}  {reason}")
    return jobs


def check_status(project_dir: Path) -> Dict[str, Any]:
    """Check live status of the running pipeline."""
    flag = project_dir / "PIPELINE_COMPLETE.flag"
    try:
        project_linux = win_to_linux_path(project_dir).rstrip("/")
    except ValueError:
        project_linux = None
    master_logs = list(project_dir.glob("snakemake/slurm_master_*.out"))
    master_ids = {m.group(1) for m in (re.match(r"slurm_master_(\d+)\.out$", p.name) for p in master_logs) if m}
    ids_file = project_dir / "snakemake" / MASTER_JOBID_FILE
    if ids_file.exists():
        master_ids |= set(ids_file.read_text(errors="ignore").split())
    res = run_ssh_cmd(f"squeue -u $USER -h -o '{SQUEUE_FORMAT}' || true")
    active_jobs = select_project_jobs(res.stdout.splitlines(), project_linux, master_ids)

    tail = ""
    if master_logs:
        latest_log = max(master_logs, key=lambda p: p.stat().st_mtime)
        try:
            with open(latest_log, "r", errors="ignore") as f:
                lines = f.readlines()
                tail = "".join(lines[-15:])
        except Exception:
            pass

    return {
        "project": project_dir.name,
        "is_complete": flag.exists(),
        "failed": (project_dir / "PIPELINE_FAILED.flag").read_text(errors="ignore").strip()
        if (project_dir / "PIPELINE_FAILED.flag").exists() else "",
        "active_jobs": active_jobs,
        "latest_log_tail": tail
    }


