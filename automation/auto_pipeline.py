def win_to_linux_path(win_path: Path) -> str:
    """Convert Windows scratch path (Z:\\...) to cluster Linux path (/lisc/data/scratch/...)."""
    p_str = str(win_path).replace("\\", "/")
    if p_str.lower().startswith("z:/neurobiology/zimmer"):
        return SCRATCH_LINUX_ROOT + p_str[len("z:/neurobiology/zimmer"):]
    if "//samba.lisc.univie.ac.at/scratch/neurobiology/zimmer" in p_str:
        idx = p_str.find("/neurobiology/zimmer")
        return SCRATCH_LINUX_ROOT + p_str[idx + len("/neurobiology/zimmer"):]
    if p_str.startswith("/lisc/"):
        return p_str
    return p_str


def linux_to_win_path(linux_path: str) -> Path:
    """Convert cluster Linux path (/lisc/data/scratch/...) to Windows scratch path (Z:\\...)."""
    l_str = linux_path.replace("\\", "/")
    if l_str.startswith(SCRATCH_LINUX_ROOT):
        rel = l_str[len(SCRATCH_LINUX_ROOT):].lstrip("/")
        return SCRATCH_WIN_ROOT / Path(rel.replace("/", "\\"))
    return Path(linux_path)


def run_ssh_cmd(cmd: str, check: bool = True) -> subprocess.CompletedProcess:
    """Run remote command on LISC cluster using OpenSSH."""
    full_cmd = ["ssh", CLUSTER_SSH_HOST, cmd]
    logger.debug(f"SSH: {cmd}")
    res = subprocess.run(full_cmd, capture_output=True, text=True)
    if check and res.returncode != 0:
        logger.error(f"Remote command failed (code {res.returncode}): {res.stderr.strip()}")
        raise RuntimeError(f"Remote command failed: {res.stderr.strip()}")
    return res


def find_latest_raw_folder() -> Path:
    """Find the newest unanalyzed raw folder in Z:\\neurobiology\\zimmer\\LeonK\\raw."""
    raw_root = SCRATCH_WIN_ROOT / "LeonK" / "raw"
    if not raw_root.exists():
        raise FileNotFoundError(f"Raw root not found: {raw_root}")

    # Look for candidate folders containing _Ch0
    candidates = []
    for root, dirs, files in os.walk(raw_root):
        if any(d.endswith("_Ch0") or "ch0" in d.lower() for d in dirs):
            candidates.append(Path(root))
        elif any(f.endswith("_Ch0.btf") or f.endswith("_Ch0.tif") for f in files):
            candidates.append(Path(root))

    if not candidates:
        raise FileNotFoundError(f"No valid raw acquisition folders found in {raw_root}")

    # Return latest modified
    latest = max(candidates, key=lambda p: p.stat().st_mtime)
    logger.info(f"Auto-detected latest raw folder: {latest}")
    return latest


def sanitize_raw_folder(raw_dir: Path) -> Path:
    """Pre-flight sanitization of raw acquisition folder."""
    if not raw_dir.exists():
        raise FileNotFoundError(f"Raw directory not found: {raw_dir}")

    # Remove illegal dots in directory name
    name = raw_dir.name
    if "." in name:
        new_name = name.replace(".", "_")
        new_path = raw_dir.parent / new_name
        logger.warning(f"Renaming directory with dots: {name} -> {new_name}")
        raw_dir = raw_dir.rename(new_path)

    # Detect channel directories
    ch0_folder, ch1_folder = None, None
    subdirs = [p for p in raw_dir.iterdir() if p.is_dir()]

    for d in subdirs:
        d_lower = d.name.lower()
        if d.name.endswith("_Ch0"):
            ch0_folder = d
        elif d.name.endswith("_Ch1"):
            ch1_folder = d
        elif "ch0" in d_lower or "red" in d_lower or "channel0" in d_lower:
            if ch0_folder is None:
                ch0_folder = d
        elif "ch1" in d_lower or "green" in d_lower or "channel1" in d_lower:
            if ch1_folder is None:
                ch1_folder = d

    # Normalize subfolder names to end strictly with _Ch0 and _Ch1
    if ch0_folder and not ch0_folder.name.endswith("_Ch0"):
        base = ch0_folder.name.split("_Ch")[0].split("-Ch")[0]
        target = raw_dir / f"{base}_Ch0"
        logger.info(f"Normalizing Ch0 name: {ch0_folder.name} -> {target.name}")
        ch0_folder = ch0_folder.rename(target)

    if ch1_folder and not ch1_folder.name.endswith("_Ch1"):
        base = ch1_folder.name.split("_Ch")[0].split("-Ch")[0]
        target = raw_dir / f"{base}_Ch1"
        logger.info(f"Normalizing Ch1 name: {ch1_folder.name} -> {target.name}")
        ch1_folder = ch1_folder.rename(target)

    # Verify channels exist
    if not (ch0_folder and ch1_folder):
        btf0 = list(raw_dir.glob("*_Ch0*.btf")) or list(raw_dir.glob("*_Ch0*.tif"))
        btf1 = list(raw_dir.glob("*_Ch1*.btf")) or list(raw_dir.glob("*_Ch1*.tif"))
        if not (btf0 and btf1):
            raise ValueError(f"Could not identify both channels (_Ch0 and _Ch1) in {raw_dir}")
        logger.info(f"Verified BigTIFF channels: {btf0[0].name}, {btf1[0].name}")
    else:
        tifs0 = list(ch0_folder.glob("*.tif"))
        tifs1 = list(ch1_folder.glob("*.tif"))
        if not (tifs0 and tifs1):
            raise ValueError(f"Missing .tif files in {ch0_folder.name} or {ch1_folder.name}")
        logger.info(f"Verified NDTiff stores: Ch0 ({len(tifs0)} tifs), Ch1 ({len(tifs1)} tifs)")

    # Ensure config.yaml
    cfg_file = raw_dir / "config.yaml"
    if not cfg_file.exists():
        logger.warning(f"config.yaml missing; generating default template in {raw_dir.name}...")
        with open(cfg_file, "w") as f:
            f.write(DEFAULT_CONFIG_YAML_CONTENT)
    else:
        logger.info("Found existing acquisition config.yaml [OK]")

    return raw_dir


def initialize_project(raw_dir: Path, output_parent_dir: Optional[Path] = None, experimenter: str = "LeonK") -> Tuple[Path, str]:
    """Initialize WBFM project on LISC cluster and configure for dual tracking."""
    raw_linux = win_to_linux_path(raw_dir)

    if output_parent_dir is None:
        date_tag = time.strftime("%Y%m%d")
        output_parent_dir = SCRATCH_WIN_ROOT / "LeonK" / f"Analysis_{date_tag}"

    output_parent_dir.mkdir(parents=True, exist_ok=True)
    out_linux_parent = win_to_linux_path(output_parent_dir)

    logger.info(f"Initializing WBFM project:")
    logger.info(f"  Raw:     {raw_linux}")
    logger.info(f"  Output:  {out_linux_parent}")

    init_cmd = (
        f"{CLUSTER_ENV_PYTHON} "
        f"{SCRATCH_LINUX_ROOT}/wbfm/code/wbfm/wbfm/scripts/0a-create_new_project.py with "
        f"parent_data_folder='{raw_linux}' "
        f"project_dir='{out_linux_parent}' "
        f"experimenter='{experimenter}'"
    )
    run_ssh_cmd(init_cmd)
    time.sleep(2)

    matching = [
        p for p in output_parent_dir.iterdir()
        if p.is_dir() and (p / "project_config.yaml").exists()
    ]
    if not matching:
        raise RuntimeError(f"No project directory found inside {output_parent_dir} after initialization")

    project_dir = max(matching, key=lambda p: p.stat().st_mtime)
    project_linux = win_to_linux_path(project_dir)
    logger.info(f"Project initialized: {project_dir.name}")

    # Set snakemake_config.yaml
    smk_cfg = project_dir / "snakemake" / "snakemake_config.yaml"
    if smk_cfg.exists():
        with open(smk_cfg, "r") as f:
            c = f.read()
        c = re.sub(r"use_barlow_tracker:\s*true", "use_barlow_tracker: false", c, flags=re.IGNORECASE)
        c = re.sub(r"barlow_model_path:\s*.*", f"barlow_model_path: {DEFAULT_BARLOW_MODEL}", c)
        with open(smk_cfg, "w") as f:
            f.write(c)
        logger.info("Configured snakemake_config.yaml: SuperGlue + Barlow dual tracking [OK]")

    return project_dir, project_linux


def submit_dual_pipeline(project_dir: Path, project_linux: str) -> str:
    """Submit the resilient master Slurm execution script."""
    worm_name = project_dir.name[:12]
    
    # Generate test YAML for ID transfer
    id_test_yaml_linux = f"{project_linux}/3-tracking/id_transfer_target.yaml"
    test_yaml_content = f"""recordings:
  - name: {project_dir.name}
    path: {project_linux}
    side: unknown
    role: predict
    include: true
"""
    # Write target YAML to project
    with open(project_dir / "3-tracking" / "id_transfer_target.yaml", "w") as f:
        f.write(test_yaml_content)

    master_script = f"""#!/bin/bash
#SBATCH --job-name=wbfm_{worm_name}
#SBATCH --output={project_linux}/snakemake/slurm_master_%j.out
#SBATCH --error={project_linux}/snakemake/slurm_master_%j.err
#SBATCH --time=48:00:00
#SBATCH --cpus-per-task=2
#SBATCH --mem=8G
#SBATCH --partition=xeon_0384

export CONDA_PREFIX={SCRATCH_LINUX_ROOT}/.conda/envs/wbfm
export PATH="$CONDA_PREFIX/bin:$PATH"
export LD_LIBRARY_PATH="$CONDA_PREFIX/lib:$LD_LIBRARY_PATH"
export OPENBLAS_NUM_THREADS=1
export OMP_NUM_THREADS=1
export MKL_NUM_THREADS=1

cd "{project_linux}/snakemake"
echo "=== WBFM Dual Tracking Master Started at $(date) on $(hostname) ==="

echo "[1/4] Unlocking Snakemake directory..."
snakemake --unlock -s pipeline.smk 2>/dev/null || true

echo "[2/4] Running Segmentation + SuperGlue Tracking + Calcium Traces..."
bash RUNME.sh -s traces
STATUS_TRACES=$?
if [ $STATUS_TRACES -ne 0 ]; then
    echo "[ERROR] Traces pipeline failed with exit code $STATUS_TRACES"
    exit $STATUS_TRACES
fi

echo "[3/4] Running Barlow Embedding (GPU) + Barlow Tracking..."
bash RUNME.sh -s barlow_tracking
STATUS_BARLOW=$?
if [ $STATUS_BARLOW -ne 0 ]; then
    echo "[WARNING] Barlow tracking exited with code $STATUS_BARLOW"
fi

echo "[4/4] Generating Automated Barlow ID Transfer Annotations..."
cd {DEFAULT_ID_TRANSFER_DIR}
python run.py \\
    --config config/pipeline_config.yaml \\
    --recordings config/recordings_leon_25deg_train.yaml \\
    --test-recordings "{id_test_yaml_linux}" \\
    --phase transfer \\
    --output "{project_linux}/3-tracking/id_transfer_output" || true

# Copy generated manual_annotation.xlsx to standard location
mkdir -p "{project_linux}/3-tracking/manual_annotation"
if [ -f "{project_linux}/3-tracking/id_transfer_output/hungarian/manual_annotation.xlsx" ]; then
    cp "{project_linux}/3-tracking/id_transfer_output/hungarian/manual_annotation.xlsx" \\
       "{project_linux}/3-tracking/manual_annotation/manual_annotation.xlsx"
    echo "[SUCCESS] Copied Hungarian predicted annotations to 3-tracking/manual_annotation/"
fi

echo "PIPELINE_COMPLETE" > "{project_linux}/PIPELINE_COMPLETE.flag"
echo "=== WBFM Dual Tracking Master Completed at $(date) ==="
"""

    remote_submission = f"cat << 'EOF' | sbatch\n{master_script}EOF"
    res = run_ssh_cmd(remote_submission)
    job_id = "UNKNOWN"
    for line in res.stdout.splitlines():
        if "Submitted batch job" in line:
            job_id = line.strip().split()[-1]
            break

    logger.info(f"Dispatched master Slurm job: ID {job_id}")
    return job_id


def check_status(project_dir: Path) -> Dict[str, Any]:
    """Check live status of the running pipeline."""
    flag = project_dir / "PIPELINE_COMPLETE.flag"
    res = run_ssh_cmd("squeue -u $USER -o '%.10i %.14j %.8T %.10M %.8m %.4C %R' | grep -E 'wbfm_|smk_|auto_|alt_barl|stardist|tracking'")
    active_jobs = [line.strip() for line in res.stdout.splitlines() if line.strip()]

    master_logs = list(project_dir.glob("snakemake/slurm_master_*.out"))
    tail = ""
    if master_logs:
        latest_log = max(master_logs, key=lambda p: p.stat().st_mtime)
        try:
            with open(latest_log, "r", errors="ignore") as f:
                lines = f.readlines()
                tail = "".join(lines[-15:])
        except Exception:
            pass

    return {
        "project": project_dir.name,
        "is_complete": flag.exists(),
        "active_jobs": active_jobs,
        "latest_log_tail": tail
    }


def verify_outputs(project_dir: Path) -> Dict[str, bool]:
    """Verify all pipeline outputs and deliverables."""
    seg_meta = project_dir / "1-segmentation" / "metadata.pickle"
    masks = project_dir / "1-segmentation" / "masks.zarr"
    tracklets = project_dir / "2-training_data" / "all_tracklets.pickle"
    sg_tracks = project_dir / "3-tracking" / "postprocessing" / "combined_3d_tracks.h5"
    bt_embed = project_dir / "3-tracking" / "barlow_tracker" / "embedding.zarr"
    bt_tracks = project_dir / "3-tracking" / "barlow_tracker" / "df_barlow_tracks.h5"
    
    traces_candidates = (
        list(project_dir.glob("4-traces/green_traces.h5")) or
        list(project_dir.glob("4-traces/paper_traces*.h5")) or
        list(project_dir.glob("4-traces/red_traces.h5")) or
        list(project_dir.glob("4-traces/traces.h5"))
    )
    annot_candidates = (
        list(project_dir.glob("3-tracking/manual_annotation/manual_annotation.xlsx")) or
        list(project_dir.glob("3-tracking/id_transfer_output/hungarian/manual_annotation.xlsx")) or
        list(project_dir.glob("3-tracking/hungarian/manual_annotation.xlsx"))
    )

    return {
        "StarDist 3D Segmentation (metadata.pickle)": seg_meta.exists() and seg_meta.stat().st_size > 0,
        "StarDist 3D Masks (masks.zarr)": masks.exists(),
        "Tracklets (all_tracklets.pickle)": tracklets.exists() and tracklets.stat().st_size > 0,
        "SuperGlue Tracks (combined_3d_tracks.h5)": sg_tracks.exists() and sg_tracks.stat().st_size > 0,
        "Barlow Embeddings (embedding.zarr)": bt_embed.exists(),
        "Barlow Tracks (df_barlow_tracks.h5)": bt_tracks.exists() and bt_tracks.stat().st_size > 0,
        "Calcium Traces (green_traces.h5)": len(traces_candidates) > 0 and traces_candidates[0].stat().st_size > 0,
        "Predicted Neuron IDs (manual_annotation.xlsx)": len(annot_candidates) > 0 and annot_candidates[0].stat().st_size > 0,
    }


def main():
    parser = argparse.ArgumentParser(description="WBFM Automated Dual-Pipeline Runner ('Go' Engine)")
    subparsers = parser.add_subparsers(dest="command", required=True)

    # go
    p_go = subparsers.add_parser("go", help="Run complete dual-tracking pipeline")
    p_go.add_argument("raw_folder", nargs="?", default=None, help="Raw data folder (or auto-detect latest)")
    p_go.add_argument("--output-parent", default=None, help="Target parent directory for projects")
    p_go.add_argument("--experimenter", default="LeonK", help="Experimenter name")

    # sanitize
    p_san = subparsers.add_parser("sanitize", help="Check and sanitize raw data folder")
    p_san.add_argument("raw_folder", help="Raw data folder")

    # status
    p_stat = subparsers.add_parser("status", help="Check status of running pipeline")
    p_stat.add_argument("project_folder", help="Project directory")

    # verify
    p_ver = subparsers.add_parser("verify", help="Verify deliverables")
    p_ver.add_argument("project_folder", help="Project directory")

    args = parser.parse_args()

    if args.command == "sanitize":
        sanitize_raw_folder(Path(args.raw_folder))

    elif args.command == "go":
        logger.info("================================================================")
        logger.info("             WBFM AUTOMATED PIPELINE: GO TRIGGERED              ")
        logger.info("================================================================")
        raw_p = Path(args.raw_folder) if args.raw_folder else find_latest_raw_folder()
        clean_raw = sanitize_raw_folder(raw_p)

        out_parent = Path(args.output_parent) if args.output_parent else None
        proj_dir, proj_linux = initialize_project(clean_raw, out_parent, args.experimenter)

        job_id = submit_dual_pipeline(proj_dir, proj_linux)
        logger.info("================================================================")
        logger.info(f"Master Slurm Job ID: {job_id}")
        logger.info(f"Project Path (Win):  {proj_dir}")
        logger.info(f"Project Path (LISC): {proj_linux}")
        logger.info("Both SuperGlue tracking and Barlow embedding are now running.")
        logger.info(f"Check status with:   python auto_pipeline.py status \"{proj_dir}\"")
        logger.info("================================================================")

    elif args.command == "status":
        s = check_status(Path(args.project_folder))
        print(f"\nProject:     {s['project']}")
        print(f"Completed:   {s['is_complete']}")
        print(f"Active Jobs: {len(s['active_jobs'])}")
        for j in s['active_jobs']:
            print(f"  {j}")
        if s['latest_log_tail']:
            print("\n--- Latest Log Output ---")
            print(s['latest_log_tail'])

    elif args.command == "verify":
        v = verify_outputs(Path(args.project_folder))
        print(f"\nDeliverables for: {Path(args.project_folder).name}")
        all_ok = True
        for k, ok in v.items():
            status_str = "[OK]" if ok else "[MISSING / PENDING]"
            print(f"  {k:<55} : {status_str}")
            if not ok:
                all_ok = False
        print("----------------------------------------------------------------")
        print("RESULT: " + ("ALL DELIVERABLES READY!" if all_ok else "SOME OUTPUTS PENDING."))

if __name__ == "__main__":
    main()
